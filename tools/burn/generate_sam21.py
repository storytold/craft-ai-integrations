#!/usr/bin/env python3
"""Regenerate the SAM 2.1 tiny Burn architecture in crates/ai-engine-burn/src/model/.

    python tools/burn/generate_sam21.py <folder with encoder.onnx and decoder.onnx>
    python tools/burn/generate_sam21.py <folder> --check     # exit 1 if the tree differs

Why a script: burn-onnx turns the published ONNX graphs into Rust, but its 0.22.0 output does not
run as emitted (five defects, patched and asserted below) and one file would be 6,000 lines. The
script is the only way that code is produced, so a reviewer can rerun it and compare.

Steps: check the two files against the sizes and SHA-256 pinned in crates/ai-burn-setup, ask the
pinned burn-onnx (the `conversion` feature of that crate) for the Rust, apply the five patches
(each must match exactly the stated number of times), drop the generated loaders (they panic on a
bad file; the runner loads weights itself and returns errors), split by submodule so no file is
over the line limit, run rustfmt and write the files.

REVISION rule: it names the compiled architecture and the converter that made its weights, and is
part of the saved-weights cache key (crates/ai-burn-setup/src/sam21.rs). Change it, here and there
together, whenever burn-onnx or Burn is bumped, a patch changes, or the source files change. A Rust
test in the engine crate fails if the two disagree.
"""
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SETUP_SAM21 = ROOT / 'crates/ai-burn-setup/src/sam21.rs'
OUT = ROOT / 'crates/ai-engine-burn/src/model'
REVISION = 'sam21-tiny-burn-0.22.1-onnx-0.22.0-v1'
BURN_ONNX = '0.22.0'
MAX_LINES = 700
# A file holding one whole submodule is split once it would pass this many lines.
SPLIT_AT = 500
# The generated forward modules need only the symbols used by their submodule. Keep this list
# explicit so Clippy can catch accidental coupling to the graph-wide prelude.
FORWARD_IMPORTS = {
    ('decoder', 1): ('s', 'Tensor', 'Int', 'Module', 'Bool'),
    ('decoder', 3): ('Tensor',),
    ('decoder', 4): ('s', 'Tensor'),
    ('encoder', 1): ('Tensor', 'Int'),
    ('encoder', 5): ('s', 'Tensor', 'Module', 'Int'),
    ('encoder', 6): ('s', 'Tensor', 'Module', 'Int'),
    ('encoder', 7): ('s', 'Tensor', 'Module', 'Int'),
    ('encoder', 8): ('s', 'Tensor', 'Module', 'Int'),
    ('encoder', 9): ('s', 'Tensor', 'Module', 'Int'),
}
HEADER = ('// @generated by tools/burn/generate_sam21.py (burn-onnx ' + BURN_ONNX +
          ' plus its patches) from the published SAM 2.1 tiny ONNX. Do not edit: rerun it.\n')
CLIPPY_ATTR = '    #[allow(clippy::let_and_return, clippy::approx_constant)]\n'
NL = '\n'


def read_raw(path):
    """A file's text with its line endings untouched (Path.read_text cannot do that before 3.13)."""
    with open(path, newline='') as f:
        return f.read()


def fail(message):
    """Stops with a message and a non-zero exit, so a wrong run never writes anything."""
    print('generate_sam21: ' + message, file=sys.stderr)
    sys.exit(1)


def pins():
    """The size and SHA-256 of each source file, read from the setup crate so there is one copy."""
    text = SETUP_SAM21.read_text()
    found = re.findall(r'"(encoder|decoder)\.onnx",\s*([\d_]+),\s*"([0-9a-f]{64})"', text)
    if sorted(n for n, _, _ in found) != ['decoder', 'encoder']:
        fail('could not read the pinned files from ' + str(SETUP_SAM21))
    if f'const REVISION: &str = "{REVISION}";' not in text:
        fail('REVISION here and in the setup crate differ; change both together')
    return {n: (int(s.replace('_', '')), h) for n, s, h in found}


def check_source(folder, name, size, sha):
    """Refuses a file that is not the exact published export the patches were written for."""
    path = folder / f'{name}.onnx'
    data = path.read_bytes()
    if len(data) != size or hashlib.sha256(data).hexdigest() != sha:
        fail(f'{path} is not the pinned SAM 2.1 tiny export (size or SHA-256 differ)')
    return path


def emit(onnx, out_dir):
    """Runs the pinned burn-onnx through the setup crate's example and returns the Rust it wrote."""
    cmd = ['cargo', 'run', '-q', '-p', 'craft-ai-burn-setup', '--features', 'conversion',
           '--example', 'generate_architecture', '-j', '8', '--', str(onnx), str(out_dir)]
    if subprocess.run(cmd, cwd=ROOT).returncode != 0:
        fail('burn-onnx failed')
    return read_raw(Path(out_dir) / (onnx.stem + '.rs')).replace('\r\n', '\n')


ZERO_FILL = re.compile(
    r'Tensor::<\n\s+1,\n\s+Int,\n\s+>::from_data\(\n\s+burn::tensor::TensorData::from\(\[0i64 as i64\]\),\n'
    r'\s+\(&self\.device, burn::tensor::DType::I64\),\n\s+\)\n\s+\.reshape\(\[1\]\)\n\s+\.expand\((sub\d+_out1)\);')
FLOAT_FILL = re.compile(
    r'Tensor::<\n\s+1,\n\s+>::from_data\(\n\s+burn::tensor::TensorData::from\(\[(\d+)f32 as f64\]\),\n'
    r'\s+\(&self\.device, burn::tensor::DType::F32\),\n\s+\)\n\s+\.reshape\(\[((?:1(?:, )?)+)\]\)\n\s+\.expand\((concat\d+_out1)\);')
WHERE_BCAST = re.compile(
    r'let (where\d+_out1) = (\w+)\.mask_where\((unsqueeze\d+_out1), (add\d+_out1)\);')
EXPAND_SHAPE = re.compile(
    r'let (expand\d+_out1) = \{\n'
    r'\s+let onnx_shape(?:\s*:\s*\[i64; \d+usize\])? = (.*?);\n'
    r'\s+let input_dims = (\w+)\.dims\(\);\n'
    r'\s+let mut shape = onnx_shape;\n'
    r'\s+#\[allow\(clippy::needless_range_loop\)\]\n'
    r'\s+for i in 0\.\.\d+usize \{\n'
    r'\s+let dim_offset = (i|\d+usize \+ i);\n'
    r'\s+if shape\[dim_offset\] == 1 && input_dims\[i\] > 1 \{\n'
    r'\s+shape\[dim_offset\] = input_dims\[i\] as i64;\n'
    r'\s+\}\n'
    r'\s+\}\n'
    r'\s+(\w+)\.expand\(shape\)\n'
    r'\s+\};', re.DOTALL)


def simplify_broadcast_shape(m):
    """Delegate repeated ONNX broadcast-shape expansion to a small, reviewable helper."""
    output, requested, dimensions, offset, tensor = m.groups()
    offset = '0' if offset == 'i' else offset.split('usize', 1)[0]
    return (f'let {output} = {{\n'
            f'            let onnx_shape = {requested};\n'
            f'            let input_dims = {dimensions}.dims();\n'
            f'            {tensor}.expand(broadcast_shape(onnx_shape, input_dims, {offset}))\n'
            '        };')


def once(text, old, new, what):
    """Replaces `old` by `new`, which must occur exactly once."""
    if text.count(old) != 1:
        fail(f'patch "{what}" matched {text.count(old)} times, expected 1')
    return text.replace(old, new)


def expect(text, pattern, repl, count, what):
    """Replaces every match of `pattern`, which must match exactly `count` times."""
    text, n = pattern.subn(repl, text)
    if n != count:
        fail(f'patch "{what}" matched {n} times, expected {count}')
    return text


def where_bcast(m):
    """Where(cond, x, y) with a condition that broadcasts: Burn's mask_where wants it full size."""
    out, x, mask, y = m.groups()
    return (f'let {out} = {{\n            let t = {x};\n            let m = {mask}.expand(t.dims());\n'
            f'            t.mask_where(m, {y})\n        }};')


def float_fill(m):
    """A float ConstantOfShape that can be empty: build it directly, Burn's expand refuses a 0."""
    rank = m.group(2).count('1')
    return (f'Tensor::<{rank}>::full({m.group(3)}.map(|d| d as usize), {m.group(1)}f32, '
            '(&self.device, burn::tensor::DType::F32));')


def patch(name, text):
    """The five burn-onnx 0.22.0 defects found on SAM 2.1 tiny. Each is asserted."""
    if name == 'encoder':
        # 1: an integer scalar divided by an Int tensor was emitted as a float divide.
        text = once(
            text, '        let div6_out1 = (gather4_out1 as f32) / div5_out1;\n',
            '        let div6_out1: Tensor<1, Int> = Tensor::<1, Int>::from_data(\n'
            '            burn::tensor::TensorData::from([gather4_out1]),\n'
            '            (&self.device, burn::tensor::DType::I64),\n'
            '        )\n        .div(div5_out1);\n', 'int scalar divide')
        # 3: Hiera's window padding is 0 when the size is a multiple of the window, and Burn's
        # expand refuses a 0 length, so make the empty tensor directly.
        text = expect(
            text, ZERO_FILL,
            r'Tensor::<1, Int>::zeros([\1[0] as usize], (&self.device, burn::tensor::DType::I64));',
            5, 'zero-length int fill')
    else:
        # 2: one_hot_fill's output rank is not inferred; the shape after it is [i64; 2].
        text = once(text, '        let onehot1_out1 = {\n', '        let onehot1_out1: Tensor<2> = {\n',
                    'one_hot rank')
        # 3 again, for the decoder's empty box placeholder.
        text = expect(text, FLOAT_FILL, float_fill, 3, 'zero-length float fill')
        # 4: a Where condition that broadcasts against its operand.
        text = expect(text, WHERE_BCAST, where_bcast, 5, 'where broadcast')
    return text


def block_end(lines, start):
    """The index of the first line at column 0 that is a closing brace, from `start`."""
    for i in range(start, len(lines)):
        if lines[i] == '}':
            return i
    fail('unbalanced generated source')


def split_items(text):
    """Cuts generated Rust into its submodule chunks and the final Model chunk."""
    lines = text.split('\n')
    starts = [i for i, line in enumerate(lines) if line == '#[derive(Module, Debug)]']
    if not starts:
        fail('no module found in the generated source')
    chunks = [lines[a:b] for a, b in zip(starts, starts[1:] + [len(lines)])]
    subs, model = chunks[:-1], chunks[-1]
    if not all(re.match(r'pub struct Submodule\d+ \{', c[1]) for c in subs):
        fail('an unexpected item sits between the submodules')
    if not model[1].startswith('pub struct Model {'):
        fail('the last item is not the Model')
    return subs, model


def uses_of(text):
    """The `use` lines of the generated header, without the loaders' (Bytes, burn_store)."""
    top = text.split("#[derive(Module, Debug)]")[0].split(NL)
    keep = [l for l in top if l.startswith("use ") and "burn_store" not in l and "::Bytes" not in l]
    if not keep:
        fail("no use lines in the generated header")
    return keep


def imports_for(text, imports):
    """Keep only names referenced by this item; the Burn prelude remains a prelude import."""
    used = []
    for line in imports:
        if line == 'use burn::prelude::*;':
            used.append(line)
            continue
        name = line.removesuffix(';').rsplit('::', 1)[-1]
        if re.search(r'\b' + re.escape(name) + r'\b', text):
            used.append(line)
    return NL.join(used) + NL


def tidy(lines):
    """Strips blank lines at the end of a chunk."""
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    return lines


def sub_files(graph, number, chunk, uses):
    """The file(s) of one submodule: whole when small, else `new` here and `forward` in a child."""
    chunk = tidy(chunk)
    name = f'part_{number:02d}'
    struct_end = block_end(chunk, 0)
    impl_start = next(i for i, line in enumerate(chunk) if line.startswith('impl Submodule'))
    impl_end = block_end(chunk, impl_start)
    fwd = next(i for i in range(impl_start, impl_end) if chunk[i].startswith('    pub fn forward'))
    while chunk[fwd - 1].startswith('    #['):
        fwd -= 1
    ident = re.match(r'pub struct (Submodule\d+)', chunk[1]).group(1)
    if len(chunk) + 8 <= SPLIT_AT:
        content = '\n'.join(chunk)
        return {f'{name}.rs': imports_for(content, uses) + '\n' + content + '\n'}
    # Fields stay private: a child module of the struct's module can still read them.
    head = ('\n'.join(chunk[:struct_end + 1]) + '\n\n' + '\n'.join(chunk[impl_start:fwd]).rstrip() +
            '\n}\n\nmod forward;\n')
    imports = ', '.join((ident, *FORWARD_IMPORTS[(graph, number)]))
    body = '\n'.join(chunk[fwd:impl_end])
    body, replaced = EXPAND_SHAPE.subn(simplify_broadcast_shape, body)
    shape_import = 'use super::super::super::broadcast_shape;\n' if replaced else ''
    child = (f'use super::{{{imports}}};\n' + shape_import +
             f'impl {ident} {{\n' + body + '\n}\n')
    return {f'{name}.rs': imports_for(head, uses) + '\n' + head,
            f'{name}/forward.rs': child}


def model_file(count, model, uses):
    """The graph folder's `mod.rs`: the submodule list, the Model struct, `new` and `forward`.

    The generated `Default`, `from_file` and `from_bytes` are left out: they panic on a bad file.
    """
    model = tidy(model)
    struct_end = block_end(model, 0)
    new_impl = next(i for i, line in enumerate(model)
                    if line == 'impl Model {' and any('pub fn new' in x for x in model[i:i + 4]))
    mods = ''.join(f'mod part_{n:02d};\nuse part_{n:02d}::Submodule{n};\n' for n in range(1, count + 1))
    content = '\n'.join(model[:struct_end + 1]) + '\n\n' + '\n'.join(model[new_impl:])
    return (imports_for(content, uses) + '\n' + mods + '\n' + '\n'.join(model[:struct_end + 1]) + '\n\n' +
            '\n'.join(model[new_impl:]) + '\n')


def render(name, text):
    """All files of one graph, by path relative to the model folder, each with the generated note."""
    subs, model = split_items(text)
    uses = uses_of(text)
    files = {}
    for n, chunk in enumerate(subs, 1):
        for path, body in sub_files(name, n, chunk, uses).items():
            files[f'{name}/{path}'] = body
    files[f'{name}/mod.rs'] = model_file(len(subs), model, uses)
    # The clippy allowance on every `forward` is made once, on the module declaration.
    return {p: HEADER + b.replace(CLIPPY_ATTR, '') for p, b in files.items()}


def top_file():
    """The model folder's `mod.rs`, which carries the revision."""
    return (HEADER +
            '//! The compiled SAM 2.1 tiny architecture. [`ARCHITECTURE_REVISION`] must equal the\n'
            '//! revision in the saved-weights cache key of `craft-ai-burn-setup`.\n\n'
            'pub mod decoder;\npub mod encoder;\n\n'
            'fn broadcast_shape<const RANK: usize, const INPUT_RANK: usize>(\n'
            '    mut requested: [i64; RANK],\n'
            '    input_dimensions: [usize; INPUT_RANK],\n'
            '    offset: usize,\n'
            ') -> [i64; RANK] {\n'
            '    for (index, input_dimension) in input_dimensions.into_iter().enumerate() {\n'
            '        let dimension = &mut requested[offset + index];\n'
            '        if *dimension == 1 && input_dimension > 1 {\n'
            '            *dimension = input_dimension as i64;\n'
            '        }\n'
            '    }\n'
            '    requested\n'
            '}\n\n'
            '#[cfg(test)]\n'
            'mod tests {\n'
            '    use super::broadcast_shape;\n\n'
            '    #[test]\n'
            '    fn broadcasts_only_singleton_dimensions_in_the_input_range() {\n'
            '        assert_eq!(broadcast_shape([1, 3, 1, 7], [5, 2], 1), [1, 3, 2, 7]);\n'
            '        assert_eq!(broadcast_shape([4, 6], [9, 3], 0), [4, 6]);\n'
            '    }\n'
            '}\n\n'
            '/// What this code was generated from; part of the saved-weights cache key.\n'
            f'pub const ARCHITECTURE_REVISION: &str = "{REVISION}";\n')


def build(folder):
    """Every generated file, formatted, as {relative path: text}."""
    known = pins()
    files = {'mod.rs': top_file()}
    with tempfile.TemporaryDirectory() as tmp:
        for name in ('encoder', 'decoder'):
            size, sha = known[name]
            onnx = check_source(folder, name, size, sha)
            files.update(render(name, patch(name, emit(onnx, Path(tmp) / name))))
        for rel, body in files.items():
            path = Path(tmp) / 'out' / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, newline='\n')
        subprocess.run(['rustfmt', '--edition', '2024', str(Path(tmp) / 'out' / 'mod.rs')],
                       check=True, cwd=ROOT)
        files = {rel: read_raw(Path(tmp) / 'out' / rel) for rel in files}
    too_long = {r: b.count('\n') for r, b in files.items() if b.count('\n') >= MAX_LINES}
    if too_long:
        fail(f'files must be under {MAX_LINES} lines: {too_long}')
    return files


USAGE = 'usage: generate_sam21.py <folder with encoder.onnx and decoder.onnx> [--check]'


def parse_args(argv):
    """Returns (folder, check). Anything starting with `--` other than `--check` is refused, so a
    mistyped read-only run (`--chek`) can never fall through to the run that rewrites the tree."""
    flags = [a for a in argv if a.startswith('--')]
    folders = [a for a in argv if not a.startswith('--')]
    if len(folders) != 1 or any(f != '--check' for f in flags):
        fail(USAGE)
    return folders[0], '--check' in flags


def main():
    """Generates and writes, or with --check compares with the tree."""
    folder, check = parse_args(sys.argv[1:])
    files = build(Path(folder))
    biggest = max(b.count('\n') for b in files.values())
    if check:
        have = ({p.relative_to(OUT).as_posix(): read_raw(p) for p in OUT.rglob('*.rs')}
                if OUT.exists() else {})
        if have != files:
            differing = sorted(set(have) ^ set(files)) or [k for k in files if have[k] != files[k]]
            fail('the tree differs from a fresh generation: ' + ', '.join(differing))
        print(f'identical: {len(files)} files, longest {biggest} lines')
        return
    if OUT.exists():
        for p in sorted(OUT.rglob('*'), reverse=True):
            p.unlink() if p.is_file() else p.rmdir()
    for rel, body in files.items():
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, newline='\n')
    print(f'wrote {len(files)} files, longest {biggest} lines')


if __name__ == '__main__':
    main()
